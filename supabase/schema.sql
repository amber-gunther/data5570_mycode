-- Creates pantry/recipes tables, status/bought-on triggers, open anon access
-- (same as the old AllowAny API), and seed_demo rows.

create table if not exists pantry (
  id bigint generated by default as identity primary key,
  name text not null,
  brand text not null default '',
  barcode text not null default '',
  quantity numeric(10, 2) not null,
  unit text not null,
  storage_zone text not null default 'pantry',
  package_state text not null default 'unopened',
  expiry_date date,
  bought_on date,
  status text not null default 'active',
  is_staple boolean not null default false,
  food_category text not null default '',
  added_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists recipes (
  id bigint generated by default as identity primary key,
  title text not null,
  notes text not null default '',
  servings integer not null default 1,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists recipe_ingredients (
  id bigint generated by default as identity primary key,
  recipe_id bigint not null references recipes (id) on delete cascade,
  name text not null,
  quantity numeric(10, 2) not null,
  unit text not null
);

create or replace function pantry_before_write()
returns trigger
language plpgsql
as $$
begin
  if new.bought_on is null then
    new.bought_on := current_date;
  end if;
  if new.status = 'thrown_out' then
    null;
  elsif new.quantity is not null and new.quantity <= 0 then
    new.status := 'used_up';
  elsif new.status = 'used_up' and new.quantity > 0 then
    new.status := 'active';
  end if;
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists pantry_before_write on pantry;
create trigger pantry_before_write
before insert or update on pantry
for each row execute procedure pantry_before_write();

alter table pantry enable row level security;
alter table recipes enable row level security;
alter table recipe_ingredients enable row level security;

drop policy if exists pantry_anon_all on pantry;
create policy pantry_anon_all on pantry
  for all
  using (true)
  with check (true);

drop policy if exists recipes_anon_all on recipes;
create policy recipes_anon_all on recipes
  for all
  using (true)
  with check (true);

drop policy if exists recipe_ingredients_anon_all on recipe_ingredients;
create policy recipe_ingredients_anon_all on recipe_ingredients
  for all
  using (true)
  with check (true);

grant select, insert, update, delete on pantry, recipes, recipe_ingredients to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;

insert into pantry (name, quantity, unit, storage_zone, food_category, status)
select 'Milk', 1.00, 'gallon', 'fridge', 'milk', 'active'
where not exists (select 1 from pantry where name = 'Milk');

insert into recipes (title, notes, servings)
select 'Scrambled eggs', 'Weeknight breakfast.', 2
where not exists (select 1 from recipes where title = 'Scrambled eggs');

insert into recipe_ingredients (recipe_id, name, quantity, unit)
select r.id, 'eggs', 4.00, 'count'
from recipes r
where r.title = 'Scrambled eggs'
  and not exists (
    select 1 from recipe_ingredients i
    where i.recipe_id = r.id and i.name = 'eggs'
  );

insert into recipe_ingredients (recipe_id, name, quantity, unit)
select r.id, 'milk', 0.25, 'cup'
from recipes r
where r.title = 'Scrambled eggs'
  and not exists (
    select 1 from recipe_ingredients i
    where i.recipe_id = r.id and i.name = 'milk'
  );
